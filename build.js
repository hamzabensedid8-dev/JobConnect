#!/usr/bin/env node
/**
 * Bundles src/worker.js with the static frontend inlined as `__ASSETS__`
 * so the whole app deploys as a single Cloudflare Worker.
 */
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import path from 'node:path';

const root = path.dirname(new URL(import.meta.url).pathname);
const publicDir = path.join(root, 'public');
const outDir = path.join(root, 'dist');

const TEXT_EXT = new Set(['.html', '.css', '.js', '.svg', '.json', '.txt', '.ico', '.webmanifest']);
const BIN_EXT = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif']);

async function collect(dir, prefix = '') {
  const assets = {};
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      Object.assign(assets, await collect(full, rel));
    } else if (TEXT_EXT.has(path.extname(entry.name).toLowerCase())) {
      assets[rel] = { text: await readFile(full, 'utf8') };
    } else if (BIN_EXT.has(path.extname(entry.name).toLowerCase())) {
      // Les images sont embarquées en base64 pour rester un seul module Worker.
      const buf = await readFile(full);
      assets[rel] = { b64: buf.toString('base64'), type: path.extname(entry.name).toLowerCase() };
    }
  }
  return assets;
}

const assets = await collect(publicDir);
if (!assets['index.html']) {
  console.error('public/index.html is missing — nothing to bundle.');
  process.exit(1);
}

let worker = await readFile(path.join(root, 'src', 'worker.js'), 'utf8');

// Inline the auxiliary ES modules: Cloudflare deploys a single module, so each
// helper file is concatenated and its import/export statements removed.
const HELPERS = ['modules.js', 'pdf.js', 'contract.js'];
const helperSource = [];
for (const file of HELPERS) {
  let source = await readFile(path.join(root, 'src', file), 'utf8');
  source = source
    .replace(/^\s*import\s[\s\S]*?from\s*'\.\/[a-z]+\.js';?\s*$/gm, '')
    .replace(/^\s*export\s*\{[\s\S]*?\};?\s*$/gm, '')
    .replace(/^export\s+(?=(async\s+function|function|const|let|class))/gm, '');
  helperSource.push(source);

  const escaped = file.replace('.', '\\.');
  const importPattern = new RegExp(`^\\s*import\\s*\\{[\\s\\S]*?\\}\\s*from\\s*'\\./${escaped}';\\s*$`, 'm');
  worker = worker.replace(importPattern, '');
}
worker = `${helperSource.join('\n\n')}\n\n${worker}`;

const banner = `/* JobConnect — generated by build.js. Do not edit dist/ by hand. */\n`;
const injection = `const __ASSETS__ = ${JSON.stringify(assets)};\n`;

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'worker.js'), banner + injection + worker, 'utf8');

const size = Buffer.byteLength(banner + injection + worker);
console.log(
  `Built dist/worker.js — ${(size / 1024).toFixed(1)} KB ` +
    `(${Object.keys(assets).length} assets: ${Object.keys(assets).join(', ')})`
);
